// Pad every row to SIZE so a short row can't skew the bitmap.
function square(grid) {
  const rows = grid.slice(0, SIZE).map((row) => row.padEnd(SIZE, ".").slice(0, SIZE));
  while (rows.length < SIZE) rows.push(".".repeat(SIZE));
  return rows;
}

