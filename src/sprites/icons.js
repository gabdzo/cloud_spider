// Pad every row to SIZE so a short row can't skew the bitmap.
function square(grid) {
  const rows = grid.slice(0, SIZE).map((row) => row.padEnd(SIZE, ".").slice(0, SIZE));
  while (rows.length < SIZE) rows.push(".".repeat(SIZE));
  return rows;
}

const ALIAS = {
  alb: "lb", instance: "ec2", eks: "cluster", region: "map",
  "control-plane": "cluster", workload: "pod", route: "lb", ingress: "lb", project: "namespace", generic: "ec2",
};
const cache = new Map();

export const ICON_NAMES = Object.keys(GRIDS);

export function icon(name) {
  const key = GRIDS[name] ? name : ALIAS[name] || "ec2";
  if (!cache.has(key)) cache.set(key, art(square(GRIDS[key]), PIP_KEY));
  return cache.get(key);
}

export function grid(name) {
  return square(GRIDS[name]);
}
