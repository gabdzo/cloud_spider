export const PERK_GRIDS = GRIDS;
export const PERK_ICONS = Object.keys(GRIDS);

export function perkGrid(name) {
  const grid = GRIDS[name] || GRIDS["perk-generic"];
  return grid.map((row) => row.padEnd(16, ".").slice(0, 16)).slice(0, 16);
}

export function perkSprite(name) {
  return perkGrid(name).map((row) => [...row].map((ch) => (ch === "." ? 0 : PERK_KEY[ch] || 0)));
}
