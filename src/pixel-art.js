// Building sprites with more detail
export function buildingShack(state, animPhase, reducedMotion) {
  const rows = Array.from({ length: 16 }, () => Array(16).fill(0));
  
  // Roof
  rows[1][7] = 1;
  rows[1][8] = 1;
  for (let x = 5; x <= 10; x += 1) rows[2][x] = 1;
  for (let x = 3; x <= 12; x += 1) rows[3][x] = 1;
  
  // Walls with texture
  for (let y = 4; y <= 13; y += 1) {
    rows[y][2] = 1;
    rows[y][13] = 1;
    for (let x = 3; x <= 12; x += 1) {
      rows[y][x] = 2;
      if ((x + y) % 5 === 0 && x > 3 && x < 12 && y > 5 && y < 11) {
        rows[y][x] = 1;
      }
    }
  }
  
  // Base
  for (let x = 2; x <= 13; x += 1) rows[14][x] = 1;
  
  // Chimney
  rows[3][11] = 1;
  rows[2][11] = 1;
  rows[1][11] = 1;
  
  // Door
  for (let y = 10; y <= 13; y += 1) {
    rows[y][6] = 1;
    rows[y][7] = 4;
    rows[y][8] = 4;
    rows[y][9] = 1;
  }
  
  // Windows based on state
  const windowPositions = [[4, 5], [10, 11]];
  for (const [x1, x2] of windowPositions) {
    for (let y = 6; y <= 7; y += 1) {
      if (state === "running") {
        rows[y][x1] = LIGHT;
        rows[y][x2] = LIGHT;
      } else if (state === "stopped") {
        // Boarded up windows
        rows[y][x1] = 1;
        rows[y][x2] = 1;
        if (y === 6) {
          rows[y][x1] = 4;
          rows[y][x2] = 4;
        }
      } else if (state === "pending") {
        if (reducedMotion) {
          rows[y][x1] = GLOW;
          rows[y][x2] = GLOW;
        } else {
          const lit = animPhase % 2 === 0 ? DARK : LIGHT;
          rows[y][x1] = lit;
          rows[y][x2] = lit;
        }
      } else if (state === "stopping") {
        if (reducedMotion) {
          rows[y][x1] = WARNING;
          rows[y][x2] = WARNING;
        } else {
          const lit = animPhase % 2 === 0 ? LIGHT : DARK;
          rows[y][x1] = lit;
          rows[y][x2] = lit;
        }
      }
    }
  }
  
  // Status indicators
  if (state === "pending") {
    rows[1][8] = reducedMotion ? GLOW : (animPhase % 2 === 0 ? 0 : GLOW);
  }
  if (state === "stopping") {
    rows[12][8] = WARNING;
  }
  
  return rows;
}

