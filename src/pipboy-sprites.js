/** @param {"healthy"|"hurting"|"broken"} state */
export function figureSvg(state, scale = 6) {
  const rows = FIGURES[state] || FIGURES.healthy;
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const path = (/** @type {string} */ ch) => rows.flatMap((row, y) => [...row].map((c, x) => (c === ch ? `M${x} ${y}h1v1h-1z` : ""))).join("");
  return `<svg class="pb-fig pb-fig-${state}" viewBox="0 0 ${w} ${h}" width="${w * scale}" height="${h * scale}" shape-rendering="crispEdges" aria-hidden="true"><path d="${path("#")}" fill="currentColor"/><path d="${path("+")}" fill="currentColor" opacity=".42"/><path d="${path("o")}" fill="var(--pb-alert, #ff5a4a)"/></svg>`;
}
