// Per-module README.md for every Pulumi program under upgrades/, generated
// from its schema (inputs, terraform-docs style), its exports (outputs), its
// package.json version and its data protection. docs/iac-robustness-plan.md
// item 11. CHANGELOG.md is hand-kept; its top entry must match the version.
//   node scripts/iac-docs.mjs          write every README
//   node scripts/iac-docs.mjs --check  exit 1 if one is stale (the test runs this)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";
import { SCHEMAS, DATA_PROJECTS } from "../upgrades/schema/stacks.js";
import { docTable } from "../upgrades/schema/core.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const up = join(root, "upgrades");

export function stacks() {
  return readdirSync(up).filter((d) => existsSync(join(up, d, "Pulumi.yaml"))).sort();
}

function sources(dir) {
  return readdirSync(dir).filter((f) => f.endsWith(".js")).map((f) => readFileSync(join(dir, f), "utf8")).join("\n");
}

export function readme(d) {
  const meta = parse(readFileSync(join(up, d, "Pulumi.yaml"), "utf8"));
  const pkg = JSON.parse(readFileSync(join(up, d, "package.json"), "utf8"));
  const schema = SCHEMAS[meta.name];
  const outputs = [...new Set([...sources(join(up, d)).matchAll(/^export const (\w+)/gm)].map((m) => m[1]))];
  const deps = Object.entries(pkg.dependencies || {}).map(([n, v]) => `\`${n}\` ${v}`).join(", ");
  return [
    `<!-- generated by scripts/iac-docs.mjs from upgrades/schema and the program; edit those, then run it -->`,
    `# ${d} (${meta.name}) v${pkg.version}`,
    "",
    String(meta.description || "").trim(),
    "",
    "## Inputs",
    "",
    "Set with `pulumi config set <key> <value>` or the STACKS card. Validated before any resource is created (upgrades/schema); the card runs the same check before it makes the stack.",
    "",
    docTable(schema),
    "",
    "## Outputs",
    "",
    outputs.length ? outputs.map((o) => `- \`${o}\``).join("\n") : "- none",
    "",
    "## Guarantees",
    "",
    `- Providers pinned: ${deps} (package-lock.json).`,
    DATA_PROJECTS.includes(meta.name) ? "- Data is protected (`protectData`, default on): a hand-run destroy or replace is refused; the card's TAKE IT DOWN unprotects first." : "- No data resources to protect.",
    "- Policy pack: `pulumi preview --policy-pack ../policy-pack`.",
    "- Tested under Pulumi mocks: upgrades/iac-matrix.json.",
    "",
    "See CHANGELOG.md.",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const stale = [];
  for (const d of stacks()) {
    const file = join(up, d, "README.md");
    const want = readme(d);
    if (check) { if (!existsSync(file) || readFileSync(file, "utf8") !== want) stale.push(d); }
    else writeFileSync(file, want);
  }
  if (stale.length) { console.error(`stale README: ${stale.join(", ")} (node scripts/iac-docs.mjs)`); process.exit(1); }
}
